-- 001_normalize_decoration_wording.sql
--
-- 目的：把 house.description 里的同义异写「精装」归一成「精装修」。
--
-- 为什么只动这一处、不动 id 18 的「简易装修」（同义异写共有两对）：
--   1. 「精装 ↔ 精装修」有评测影响。L3-010 / L4-006 的黄金用 `%精装%` 匹配，
--      而 `%精装%` 天然也匹配「精装修」。于是写 `%精装修%` 的模型会漏掉 id 45
--      而被判错 —— **用词更完整反而被判错**。归一后两种写法给同样的答案。
--   2. 「简单装修 ↔ 简易装修」（id 1 / id 18）**没有任何用例涉及**，
--      改了不影响任何判定，属于纯数据卫生，故本轮不动。
--      要动的话照抄本文件的形状即可，但请先确认没有用例引用这两个词。
--
-- 背景与实测数据见 docs/项目B_评测改动说明_R5.md §8.11。
--
-- 影响面（执行前后都必须复核，命令见 R5 §9）：
--   %精装%   6 套（3/8/11/29/31/45）  → 不变（45 仍含"精装"二字）
--   %精装修% 5 套（3/8/11/29/31）     → 6 套（并入 45）
--   L3-010 黄金 6 套、L4-006 黄金 8 套 → 均不变
--
-- 幂等：WHERE 里钉了**完整的旧值**而不是 LIKE，重复执行影响 0 行。
--   刻意不用 `LIKE '%精装%'` 这种宽条件：将来若有人把该行改成别的措辞，
--   宽条件会连带覆盖未知内容，而这里只该改我核实过的那一行。
--   代价是"若该行已被改成第三种措辞，本文件静默 0 行"——这是安全的失败方向
--   （不覆盖未知内容），执行时请核对输出的 affected rows 是否为 1。
--
-- 执行：.\venv\Scripts\python.exe eval\tools\apply_sql.py sql\001_normalize_decoration_wording.sql --yes
--   （不带 --yes 是空跑，只打印语句不提交；本文件用**可写账号**DB_USER 连接）

UPDATE house
   SET description = '有电梯，近4号线，精装修三房'
 WHERE id = 45
   AND description = '有电梯，近4号线，精装三房';
